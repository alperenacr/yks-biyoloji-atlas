// --- Theme Management ---

final themeProvider = StateNotifierProvider<ThemeNotifier, ThemeMode>((ref) {
  final prefs = ref.watch(sharedPreferencesProvider);
  return ThemeNotifier(prefs);
});

class ThemeNotifier extends StateNotifier<ThemeMode> {
  final _prefs;
  static const _themeKey = 'theme_mode';

  ThemeNotifier(this._prefs) : super(_loadTheme(_prefs));

  static ThemeMode _loadTheme(prefs) {
    final isDark = prefs.getBool(_themeKey) ?? false;
    return isDark ? ThemeMode.dark : ThemeMode.light;
  }

  void toggleTheme() {
    state = state == ThemeMode.light ? ThemeMode.dark : ThemeMode.light;
    _prefs.setBool(_themeKey, state == ThemeMode.dark);
  }
}

// --- Language Management ---

final languageProvider = StateNotifierProvider<LanguageNotifier, String>((ref) {
  final prefs = ref.watch(sharedPreferencesProvider);
  return LanguageNotifier(prefs);
});

class LanguageNotifier extends StateNotifier<String> {
  final _prefs;
  static const _langKey = 'language_code';

  LanguageNotifier(this._prefs) : super(_loadLanguage(_prefs));

  static String _loadLanguage(prefs) {
    return prefs.getString(_langKey) ?? 'tr';
  }

  void setLanguage(String langCode) {
    state = langCode;
    _prefs.setString(_langKey, langCode);
  }
}

